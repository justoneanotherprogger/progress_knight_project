import yaml
from pathlib import Path

BASE_DIR = Path(__file__).parent
LOCALES_DIR = BASE_DIR / "locales"
OUTPUT_FILE = BASE_DIR / "js" / "i18n.js"

def load_locale(lang: str) -> dict:
    """Load locale data from YAML file."""
    locale_file = LOCALES_DIR / f"{lang}.yaml"
    with open(locale_file, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)

def generate_js():
    """Generate i18n.js with all locale data embedded."""
    locales = {}
    for lang_file in LOCALES_DIR.glob("*.yaml"):
        lang = lang_file.stem
        locales[lang] = load_locale(lang)

    # Create a JS-safe representation
    locales_js = repr(locales)

    js_content = f"""// Auto-generated by build.py - do not edit manually
const I18N = {locales_js};
const DEFAULT_LANG = 'en';

function getBrowserLang() {{
    const lang = (navigator.language || 'en').toLowerCase();
    for (const key of Object.keys(I18N)) {{
        if (lang.startsWith(key)) return key;
    }}
    return DEFAULT_LANG;
}}

let currentLang = localStorage.getItem('lang') || getBrowserLang();

function t(key) {{
    const langData = I18N[currentLang] || I18N[DEFAULT_LANG];
    return langData[key] || I18N[DEFAULT_LANG][key] || key;
}}

function setLang(lang) {{
    if (I18N[lang]) {{
        currentLang = lang;
        localStorage.setItem('lang', lang);
        document.documentElement.lang = lang;
        updateLangButtons();
        applyTranslations();
    }}
}}

function updateLangButtons() {{
    document.querySelectorAll('.lang-btn').forEach(btn => {{
        const btnLang = btn.getAttribute('data-lang') || btn.textContent.toLowerCase().trim();
        if (btnLang === currentLang) {{
            btn.classList.add('selected');
        }} else {{
            btn.classList.remove('selected');
        }}
    }});
}}

function applyTranslations() {{
    document.querySelectorAll('[data-i18n]').forEach(el => {{
        const key = el.getAttribute('data-i18n');
        el.innerHTML = t(key);
    }});
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {{
        const key = el.getAttribute('data-i18n-placeholder');
        el.setAttribute('placeholder', t(key));
    }});
    document.dispatchEvent(new CustomEvent('i18n:changed', {{ detail: {{ lang: currentLang }} }}));
}}

document.addEventListener('DOMContentLoaded', () => {{
    applyTranslations();
    updateLangButtons();
}});
"""

    OUTPUT_FILE.write_text(js_content, encoding="utf-8")
    print(f"Generated {OUTPUT_FILE} with languages: {', '.join(locales.keys())}")

if __name__ == "__main__":
    generate_js()
